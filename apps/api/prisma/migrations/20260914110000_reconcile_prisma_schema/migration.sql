-- Reconcile the migrated schema with schema.prisma (production-gate audit).
--
-- WHY THIS MIGRATION EXISTS
-- ------------------------
-- The migration chain and schema.prisma had drifted apart in both directions,
-- and nine models declared in schema.prisma had no migration creating their
-- tables at all (Document, DocumentVersion, Resource, ResourceBooking,
-- FeatureFlag, DataQualityIssue, ReceiptCounter, TelegramLinkLog,
-- NotificationDedup). The application code uses every one of them, so a
-- database built from the previous chain crashed with P2021 on those features.
--
-- DataQualityIssue additionally had to be restored: migration
-- 20260909150000_schema_purge_consolidation dropped it as an orphan, but
-- data-quality.service.ts (17 call sites), security.service.ts and the Data
-- Quality Center screen all query it.
--
-- The remainder of this file is the SQL generated by
--   prisma migrate diff --from-url <migrated database> --                       --to-schema-datamodel prisma/schema.prisma --script
-- applied verbatim. It fixes, in order:
--   * the nine missing tables (+ their indexes and foreign keys);
--   * columns that schema.prisma declares but the hand-written migrations never
--     created (e.g. DeviceToken.organizationId, ParentStudent.userId,
--     AutomationExecution.triggerPayload/result/startedAt, FinancialPeriod.endDate);
--   * referential actions: the hand-written migrations used ON DELETE CASCADE
--     where schema.prisma requires RESTRICT for required relations, and omitted
--     ON UPDATE CASCADE;
--   * DEFAULT values and TIMESTAMP precision that deviated from the schema
--     (Prisma generates UUIDs client-side and uses TIMESTAMP(3)).
--
-- After this migration the chain reproduces schema.prisma exactly: the same
-- diff run against a freshly migrated database returns zero statements.
--
-- SAFETY: the only destructive statements are DROP CONSTRAINT / DROP INDEX /
-- ALTER COLUMN ... DROP DEFAULT and TIMESTAMP precision narrowing on columns
-- that the previous chain created with a wider precision. No table is dropped
-- and no column is removed.

